//! The ESS reference pages under `website/docs/reference/ess/`, from `ess generate --kind docs`.

/// The line every generated Markdown page carries directly after its front matter.
pub const HEADER: &str = "<!-- generated by thalamus-docs, do not edit -->";
/// The same line in an MDX page, where HTML comments are not allowed.
pub const MDX_HEADER: &str = "{/* generated by thalamus-docs, do not edit */}";
/// Where the published JSON Schemas are served, below the site's base URL.
pub const SCHEMA_URL: &str = "https://beyond10x.github.io/thalamus/schemas/";

/// Strip the leading HTML comment `ess generate` writes, returning the rest.
fn strip_ess_banner(page: &str) -> Result<&str, String> {
    let rest = page
        .strip_prefix("<!--")
        .ok_or("ess page does not open with its provenance comment")?;
    let end = rest
        .find("-->")
        .ok_or("ess provenance comment is not closed")?;
    Ok(rest[end + 3..].trim_start_matches('\n'))
}

/// The H1 title and the first paragraph after it.
fn title_and_summary(body: &str) -> Result<(String, String), String> {
    let mut lines = body.lines();
    let title = lines
        .next()
        .and_then(|line| line.strip_prefix("# "))
        .ok_or("ess page does not open with a level-one heading")?
        .trim()
        .to_owned();
    let summary = lines
        .skip_while(|line| line.trim().is_empty())
        .take_while(|line| !line.trim().is_empty())
        .collect::<Vec<_>>()
        .join(" ");
    if summary.is_empty() {
        return Err(format!("ess page {title} has no summary"));
    }
    Ok((title, summary))
}

fn yaml_string(value: &str) -> String {
    format!("\"{}\"", value.replace('\\', "\\\\").replace('"', "\\\""))
}

fn front_matter(title: &str, label: &str, description: &str, position: Option<u32>) -> String {
    let position = position.map_or(String::new(), |n| format!("sidebar_position: {n}\n"));
    format!(
        "---\ntitle: {}\nsidebar_label: {}\n{position}description: {}\ncustom_edit_url: null\n---\n\n",
        yaml_string(title),
        yaml_string(label),
        yaml_string(description),
    )
}

/// One domain page of `ess generate --kind docs`, rewritten as a site page: `(title, summary,
/// page)`. The level-one heading is dropped so the front matter's title heads the page.
pub fn domain_page(source: &str) -> Result<(String, String, String), String> {
    let body = strip_ess_banner(source)?;
    let (title, summary) = title_and_summary(body)?;
    let body = body
        .split_once('\n')
        .map_or("", |(_, rest)| rest)
        .trim_start_matches('\n')
        .replace(
            "[Back to the index](../index.md)",
            "[All domains](./index.mdx)",
        )
        .replace("`ess generate`", "`task generate`");
    if body.contains("](../") {
        return Err(format!(
            "ess page {title} links outside the generated domain pages"
        ));
    }
    let page = front_matter(
        &format!("{title} domain"),
        &title,
        &format!("ESS reference for the {title} domain, generated from the specification."),
        None,
    ) + HEADER
        + "\n\n"
        + &body;
    Ok((title, summary, page))
}

/// One domain as the index lists it.
pub struct DomainEntry {
    pub page: String,
    pub graph: String,
    pub title: String,
    pub summary: String,
}

/// One published JSON Schema: the entity's short name and the file under `static/schemas/`.
pub struct SchemaEntry {
    pub entity: String,
    pub file: String,
}

/// The reference index: the whole model as one graph, one `<DomainGraph>` per domain with a link
/// to its full page, and the published JSON Schemas.
pub fn index_page(system_graph: &str, domains: &[DomainEntry], schemas: &[SchemaEntry]) -> String {
    let mut page = front_matter(
        "ESS specification",
        "ESS specification",
        "The thalamus specification, domain by domain, generated from spec/ in the repository.",
        Some(1),
    ) + MDX_HEADER
        + "\n\n";
    page.push_str(&format!(
        "import systemGraph from '@site/data/ess/{system_graph}';\n"
    ));
    for (n, domain) in domains.iter().enumerate() {
        page.push_str(&format!(
            "import domainGraph{n} from '@site/data/ess/{}';\n",
            domain.graph
        ));
    }
    page.push_str("\n# ESS specification\n\n");
    page.push_str(
        "thalamus is specified in ESS before it is implemented. This page and the domain pages \
         below are generated from the repository's `spec/` directory by `thalamus-docs`: the \
         graphs from `ess specify compile`, the pages from `ess generate --kind docs`. They change \
         when the specification changes, and `task check` fails if they fall behind it.\n\n\
         The Rust model (`generated/thalamus-model`) and the serde types of every record \
         (`generated/spec-types`) are generated from the same files. The \
         [contract explorer](./explorer.mdx) shows the whole specification in one searchable \
         view.\n\n\
         ## The whole model\n\n\
         Every entity and every relation across the five domains. An arrow is a relation, \
         labelled with its name; a lifecycle lists the states an entity moves through.\n\n\
         <DomainGraph data={systemGraph} title=\"thalamus\" />\n",
    );
    for (n, domain) in domains.iter().enumerate() {
        page.push_str(&format!(
            "\n## {title}\n\n{summary}\n\n<DomainGraph data={{domainGraph{n}}} title=\"{title}\" />\n\n\
             [Read the {title} domain in full](./{file})\n",
            title = domain.title,
            summary = domain.summary,
            file = domain.page,
        ));
    }
    page.push_str(
        "\n## JSON Schemas\n\n\
         One JSON Schema per entity, generated by `ess generate --kind schema`. Each is \
         self-contained: every type it uses is under its `$defs`.\n\n\
         | entity | schema |\n|---|---|\n",
    );
    for schema in schemas {
        page.push_str(&format!(
            "| `{entity}` | [`{file}`]({SCHEMA_URL}{file}) |\n",
            entity = schema.entity,
            file = schema.file,
        ));
    }
    page
}

/// The contract explorer: Docs System's `EssContractViewer` over the `ess-docs/1` document.
pub fn explorer_page(document: &str) -> String {
    let mut page = front_matter(
        "Contract explorer",
        "Contract explorer",
        "Search and browse every entity, command, event and lifecycle of the thalamus specification.",
        Some(2),
    ) + MDX_HEADER
        + "\n\n";
    page.push_str(&format!(
        "import {{EssContractViewer}} from '@beyond10x/docs-system/ess-contract-viewer';\n\
         import contract from '@site/data/ess/{document}';\n\n\
         # Contract explorer\n\n\
         The whole specification in one searchable view: every domain, entity, command, event and \
         lifecycle, from the `ess-docs/1` document `ess generate --kind docs-ir` writes. The \
         [domain pages](./index.mdx) hold the same content page by page.\n\n\
         <EssContractViewer document={{contract}} id=\"thalamus\" title=\"thalamus contracts\" \
         sourceRepository=\"https://github.com/beyond10x/thalamus/tree/main/spec\" />\n"
    ));
    page
}

/// `SignalDefinition` → `signal-definition`.
pub fn kebab(name: &str) -> String {
    let mut out = String::new();
    for (n, c) in name.chars().enumerate() {
        if c.is_ascii_uppercase() {
            if n > 0 {
                out.push('-');
            }
            out.push(c.to_ascii_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    const SAMPLE: &str = "<!--\ngenerated from thalamus v1\ndo not edit: regenerate with `ess generate`\n-->\n\n# Samples\n\nOne reading of one signal.\nAppend-only.\n\n`thalamus.observation` is one of thalamus's bounded contexts. [Back to the index](../index.md).\n\nSee [`SignalDefinition`](thalamus-definition.md#signaldefinition).\n\nDo not edit this file; regenerate it with `ess generate`.\n";

    #[test]
    fn domain_pages_carry_the_header_and_no_ess_banner() {
        let (title, summary, page) = domain_page(SAMPLE).unwrap();
        assert_eq!(title, "Samples");
        assert_eq!(summary, "One reading of one signal. Append-only.");
        assert!(page.starts_with("---\ntitle: \"Samples domain\"\n"));
        assert!(page.contains("custom_edit_url: null\n"));
        assert!(page.contains(&format!("{HEADER}\n\nOne reading of one signal.")));
        assert!(!page.contains("<!--\ngenerated from"));
        assert!(!page.contains("# Samples\n"));
        assert!(page.contains("[All domains](./index.mdx)"));
        assert!(page.contains("(thalamus-definition.md#signaldefinition)"));
        assert!(page.contains("`task generate`"));
        assert!(!page.contains("`ess generate`"));
    }

    #[test]
    fn links_out_of_the_domain_set_are_refused() {
        let page = SAMPLE.replace("bounded contexts.", "bounded contexts. [x](../topology.md)");
        assert!(domain_page(&page).is_err());
    }

    #[test]
    fn index_renders_the_system_graph_one_graph_per_domain_and_the_schemas() {
        let page = index_page(
            "thalamus.domain-graph.json",
            &[DomainEntry {
                page: "thalamus-observation.md".into(),
                graph: "thalamus-observation.domain-graph.json".into(),
                title: "Samples".into(),
                summary: "One reading.".into(),
            }],
            &[SchemaEntry {
                entity: "SignalSample".into(),
                file: "signal-sample.schema.json".into(),
            }],
        );
        assert!(page.contains(MDX_HEADER));
        assert!(
            page.contains("import systemGraph from '@site/data/ess/thalamus.domain-graph.json';")
        );
        assert!(page.contains("<DomainGraph data={systemGraph} title=\"thalamus\" />"));
        assert!(page.contains(
            "import domainGraph0 from '@site/data/ess/thalamus-observation.domain-graph.json';"
        ));
        assert!(page.contains("<DomainGraph data={domainGraph0} title=\"Samples\" />"));
        assert!(page.contains("[Read the Samples domain in full](./thalamus-observation.md)"));
        assert!(page.contains(
            "| `SignalSample` | [`signal-sample.schema.json`](https://beyond10x.github.io/thalamus/schemas/signal-sample.schema.json) |"
        ));
    }

    #[test]
    fn the_explorer_renders_the_contract_viewer_over_the_document() {
        let page = explorer_page("thalamus.ess-docs.json");
        assert!(page.starts_with("---\ntitle: \"Contract explorer\"\n"));
        assert!(page.contains(MDX_HEADER));
        assert!(page.contains(
            "import {EssContractViewer} from '@beyond10x/docs-system/ess-contract-viewer';"
        ));
        assert!(page.contains("import contract from '@site/data/ess/thalamus.ess-docs.json';"));
        assert!(page.contains("<EssContractViewer document={contract} id=\"thalamus\""));
    }

    #[test]
    fn entity_names_become_kebab_file_names() {
        assert_eq!(kebab("SignalDefinition"), "signal-definition");
        assert_eq!(kebab("Assertion"), "assertion");
        assert_eq!(kebab("DimensionRegistry"), "dimension-registry");
    }
}
